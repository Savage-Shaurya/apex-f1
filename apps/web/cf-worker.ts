// Worker entry (wrangler.jsonc "main"): the OpenNext worker plus what Vercel did for us.
// 1. Cron Triggers replace vercel.json crons: each schedule calls its /api/cron route in-process
//    with the CRON_SECRET bearer, exactly as Vercel Cron did.
// 2. Any host other than apex.snappycrew.com (the *.workers.dev copy) gets X-Robots-Tag: noindex.
// 3. cf-fetch-shim: Workers reject fetch(..., { redirect: 'error' }), which every provider call uses.
import './cf-fetch-shim';
// @ts-ignore .open-next/worker.js is generated by `opennextjs-cloudflare build`
import { default as handler } from './.open-next/worker.js';

type WorkerEnv = { CRON_SECRET?: string } & Record<string, unknown>;
type Ctx = { waitUntil(p: Promise<unknown>): void };

const PROD_HOST = 'apex.snappycrew.com';
const CRONS: Record<string, string> = {
  '0 3 * * *': '/api/cron/jolpica-nightly',
  '0 4 * * *': '/api/cron/youtube-sync',
  '0 6 * * 5': '/api/cron/newsletter-blast',
};

export default {
  async fetch(request: Request, env: WorkerEnv, ctx: Ctx): Promise<Response> {
    const res: Response = await handler.fetch(request, env, ctx);
    if (new URL(request.url).hostname === PROD_HOST) return res;
    const out = new Response(res.body, res);
    out.headers.set('X-Robots-Tag', 'noindex, nofollow');
    return out;
  },

  async scheduled(event: { cron: string }, env: WorkerEnv, ctx: Ctx): Promise<void> {
    const path = CRONS[event.cron];
    if (!path || !env.CRON_SECRET) {
      console.log(JSON.stringify({ event: 'cron.skipped', cron: event.cron, reason: path ? 'no CRON_SECRET' : 'unknown schedule' }));
      return;
    }
    const req = new Request(`https://${PROD_HOST}${path}`, { headers: { authorization: `Bearer ${env.CRON_SECRET}` } });
    const res: Response = await handler.fetch(req, env, ctx);
    console.log(JSON.stringify({ event: 'cron.done', path, status: res.status }));
  },
};

